// Generates app/dark-palette.css: dark mode for every Tailwind colour, with
// no dark: classes in the components.
//
// Tailwind 4's colour utilities read CSS variables (text-zinc-900 is
// color: var(--color-zinc-900)), so redefining the variables recolours the
// whole app. Each shade gets light-dark(<itself>, <its mirror>): 50 <-> 950,
// 100 <-> 900, ... 500 stays. Dark text on light cards becomes light text
// on dark cards, and accents keep their hue at the matching contrast. The
// browser picks the side from color-scheme (set in globals.css).
//
// Run after upgrading Tailwind:  node scripts/generate-dark-palette.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const themeCss = readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8');

const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const mirror = (shade) => SHADES[SHADES.length - 1 - SHADES.indexOf(shade)];

// --color-<palette>-<shade>: <value>;
const palettes = new Map();
for (const [, palette, shade, value] of themeCss.matchAll(
  /--color-([a-z]+)-(\d+):\s*([^;]+);/g
)) {
  if (!palettes.has(palette)) palettes.set(palette, {});
  palettes.get(palette)[shade] = value.trim();
}

const lines = [];
for (const [palette, shades] of palettes) {
  if (!SHADES.every((s) => s in shades)) continue; // only full 50-950 scales
  for (const shade of SHADES) {
    lines.push(
      `  --color-${palette}-${shade}: light-dark(${shades[shade]}, ${shades[mirror(shade)]});`
    );
  }
}

const zinc = palettes.get('zinc');
const css = `/* GENERATED by scripts/generate-dark-palette.mjs -- edit that, not this. */
/* Every Tailwind colour as light-dark(<light>, <mirrored shade>); see the
   script for why. Unlayered, so it overrides Tailwind's theme layer. */

:root {
  /* bg-white is the cards; in the dark they sit one step above the page
     (--background, zinc-950), and text-white turns dark on light buttons. */
  --color-white: light-dark(#fff, ${zinc['900']});
  --color-black: light-dark(#000, #fff);
${lines.join('\n')}
}
`;

writeFileSync(new URL('../app/dark-palette.css', import.meta.url), css);
console.log(`app/dark-palette.css: ${palettes.size} palettes, ${lines.length} shades`);
